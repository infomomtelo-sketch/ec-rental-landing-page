"use strict";
/**
 * inspect-audit-gate.js — Tello Inspect audit: browser gate UI.
 *
 * Framework-free. Plant requirements (see SPEC.md):
 *  - each room card:            <div data-room="Bedroom 2"> ... </div>
 *  - each room's upload input:  <input type="file" data-upload-for="Bedroom 2">
 *  - finalize/sign button(s):   <button data-finalize> ... </button>
 *  - a container:               <div id="audit-gate"></div>
 *  - the server renders (or the page fetches) the gate state and calls
 *        TelloInspectGate.render(gateState)
 *    where gateState = { status, validation_errors, override } as stored
 *    by audit-endpoint.js. Call render() again after every audit run and
 *    after every photo upload (uploads reset the gate server-side; the
 *    fresh state comes back with the upload response).
 *  - override confirmation POSTs to /api/inspections/:id/audit-override
 *    with { note } — the server stamps by/at and re-renders.
 *  - render(state, opts) opts:
 *      viewer: "landlord" | "tenant"        (who is looking at the page)
 *      initiatedBy: "landlord" | "tenant_link" (how the inspection began)
 *      overrideEndpoint, ackEndpoint: the two POST routes.
 *    The Landlord Override toggle is rendered ONLY when viewer is the
 *    landlord AND the inspection was landlord-initiated. Tenant-submitted
 *    links never contain it. Coverage warnings render for everyone;
 *    only a landlord session gets the acknowledge button.
 */
(function () {
  const DISCLAIMER_TEXT = "AI photo condition review generated by Tello Inspect. Not a licensed home inspection. All maintenance, fault, and deposit determinations are made solely by the landlord.";
  const STYLE = `
    .audit-warnings{border:2px solid #b58900;background:#fdf8e7;border-radius:12px;padding:16px;margin:16px 0}
    .audit-warning{margin:8px 0;padding:10px 12px;background:#fff;border-left:4px solid #b58900;border-radius:6px;font-size:16px}
    .audit-blocked{border:2px solid #b3261e;background:#fdf3f2;border-radius:12px;padding:16px;margin:16px 0}
    .audit-blocked h3{color:#b3261e;margin:0 0 8px;font-size:20px}
    .audit-error{margin:8px 0;padding:10px 12px;background:#fff;border-left:4px solid #b3261e;border-radius:6px;font-size:16px}
    .audit-error b{display:block}
    .audit-passed{border:2px solid #137333;background:#eef7ee;border-radius:12px;padding:16px;margin:16px 0}
    .room-needs-attention{outline:3px solid #b3261e !important;outline-offset:2px}
    .room-needs-attention::before{content:"Needs attention";display:inline-block;background:#b3261e;color:#fff;
      font-size:13px;font-weight:700;padding:2px 8px;border-radius:999px;margin:4px}
    .audit-retake,.audit-override-btn{min-height:48px;font-size:17px;font-weight:700;border-radius:10px;padding:10px 18px;cursor:pointer}
    .audit-retake{background:#b3261e;color:#fff;border:none;margin-top:10px}
    .audit-override{margin-top:16px;border-top:1px solid #e0b4b0;padding-top:12px}
    .audit-override textarea{width:100%;min-height:72px;font-size:16px;padding:10px;border-radius:8px;border:1px solid #999}
    .audit-override-btn{background:#fff;color:#7a1a14;border:2px solid #7a1a14;margin-top:8px}
    button[data-finalize][disabled]{opacity:.45;cursor:not-allowed}
  `;

  function ensureStyle() {
    if (!document.getElementById("audit-gate-style")) {
      const s = document.createElement("style");
      s.id = "audit-gate-style";
      s.textContent = STYLE;
      document.head.appendChild(s);
    }
  }

  function esc(text) {
    const d = document.createElement("div");
    d.textContent = String(text == null ? "" : text);
    return d.innerHTML;
  }

  function flaggedRooms(errors) {
    const rooms = [];
    for (const e of errors || []) {
      if (e.room && !rooms.includes(e.room)) rooms.push(e.room);
    }
    return rooms;
  }

  function setFinalizeLocked(locked, reasonText) {
    document.querySelectorAll("[data-finalize]").forEach((btn) => {
      btn.disabled = locked;
      if (locked) {
        btn.setAttribute("aria-disabled", "true");
        if (reasonText) btn.title = reasonText;
      } else {
        btn.removeAttribute("aria-disabled");
        btn.removeAttribute("title");
      }
    });
    // The sign section itself stays hidden until the gate opens.
    const sign = document.querySelector("[data-sign-section]");
    if (sign) sign.style.display = locked ? "none" : "";
  }

  function highlightRooms(rooms) {
    document.querySelectorAll("[data-room]").forEach((el) => {
      el.classList.toggle("room-needs-attention", rooms.includes(el.getAttribute("data-room")));
    });
  }

  function focusRoom(room) {
    const input = document.querySelector(`[data-upload-for="${CSS.escape(room)}"]`);
    const card = document.querySelector(`[data-room="${CSS.escape(room)}"]`);
    const target = card || (input && input.closest("div"));
    if (target) target.scrollIntoView({ behavior: "smooth", block: "center" });
    if (input) setTimeout(() => input.click(), 450);
  }

  /**
   * @param {{status:string, validation_errors:Array, override:?object}} state
   * @param {{overrideEndpoint?:string, onOverrideSaved?:function}} [opts]
   */
  function render(state, opts = {}) {
    ensureStyle();
    const box = document.getElementById("audit-gate");
    if (!box || !state) return;
    const errors = state.validation_errors || [];
    const rooms = flaggedRooms(errors);

    function wireAck() {
      const ackBtn = document.getElementById("audit-ack-btn");
      if (!ackBtn) return;
      ackBtn.addEventListener("click", async () => {
        if (!opts.ackEndpoint) { alert("Warning acknowledgment endpoint is not wired yet."); return; }
        const res = await fetch(opts.ackEndpoint, { method: "POST", headers: { "Content-Type": "application/json", "Authorization": "Bearer " + (window.localStorage ? localStorage.getItem("ec_token") : "") }, body: "{}" });
        if (!res.ok) { alert("The warnings could not be acknowledged. The report stays locked."); return; }
        const fresh = await res.json();
        if (opts.onOverrideSaved) opts.onOverrideSaved(fresh);
        render(fresh, opts);
      });
    }

    const warnings = state.coverage_warnings || [];
    const ack = state.audit_warnings_ack;
    const warningsAcked = warnings.length === 0 || Boolean(ack && Array.isArray(ack.warnings_acknowledged) &&
      warnings.every((w) => ack.warnings_acknowledged.some((a) => a.space === w.space && a.warning_type === w.warning_type)));
    const isLandlord = opts.viewer === "landlord";
    // OVERRIDE ACCESS: landlord-initiated sessions only. Tenant-submitted
    // links never see the toggle (and the server 403s it regardless).
    const overrideAllowed = isLandlord && opts.initiatedBy === "landlord";
    const warningsHtml = warnings.length ? `
      <div class="audit-warnings">
        <h3>Coverage warnings (${warnings.length})</h3>
        <p>These spaces are inferred from the property's size and type. They do not block the audit,
           but the report can only be finalized once they are photographed or acknowledged.</p>
        ${warnings.map((w) => `<div class="audit-warning"><b>${esc(w.space)}</b> — ${esc(w.description)}</div>`).join("")}
        ${warningsAcked
          ? `<p>Acknowledged by ${esc(ack.by)} on ${esc(new Date(ack.at).toLocaleString())}.</p>`
          : isLandlord
            ? `<button type="button" class="audit-override-btn" id="audit-ack-btn">Acknowledge warnings and continue</button>`
            : `<p>Your landlord will review these warnings.</p>`}
      </div>` : "";

    if (state.status === "PASSED") {
      box.innerHTML = `<div class="audit-passed"><h3>Photo audit passed</h3>
        <p>Every required room and angle is documented.${warningsAcked ? " You can review and sign the report." : " Acknowledge the coverage warnings below to unlock signing."}</p>
        <p><i>${esc(DISCLAIMER_TEXT)}</i></p></div>` + warningsHtml;
      highlightRooms([]);
      setFinalizeLocked(!warningsAcked, warningsAcked ? "" : "Coverage warnings are not acknowledged yet.");
      wireAck();
      return;
    }

    if (state.status === "PASSED_WITH_OVERRIDE" && state.override) {
      box.innerHTML = `<div class="audit-passed"><h3>Finalized under Landlord Override</h3>
        <p>Overridden on ${esc(new Date(state.override.at).toLocaleString())} by ${esc(state.override.by)}.
        Note: ${esc(state.override.note)}</p></div>`;
      highlightRooms(rooms);
      setFinalizeLocked(false);
      return;
    }

    // Blocked: NOT_RUN also lands here with whatever errors are stored.
    // Errors are shown VERBATIM: description + the exact required action.
    const list = errors.map((e) =>
      `<div class="audit-error"><b>${esc(e.room)} — ${esc(String(e.error_type || "").replaceAll("_", " "))}</b>` +
      `${esc(e.description)}<br><b>Needed:</b> ${esc(e.required_action || "")}</div>`
    ).join("");
    // The override block exists ONLY on landlord-initiated sessions
    // viewed by the landlord. Tenant-submitted links get no toggle in
    // the DOM at all (and the server refuses the call regardless).
    const overrideHtml = overrideAllowed ? `
        <div class="audit-override">
          <label><input type="checkbox" id="audit-override-toggle"> <b>Landlord Override</b> —
            finalize anyway. The override, your note, and this error list are printed on the report.</label>
          <div id="audit-override-form" style="display:none">
            <textarea id="audit-override-note" placeholder="Why is this report being finalized despite the problems above? (required)"></textarea>
            <button type="button" class="audit-override-btn" id="audit-override-confirm">
              Record override and unlock signing</button>
          </div>
        </div>` : "";
    box.innerHTML = `
      <div class="audit-blocked" role="alert">
        <h3>This report can't be finalized yet</h3>
        <p>The photo audit found ${errors.length} problem${errors.length === 1 ? "" : "s"}.
           Fix each one, then run the audit again.</p>
        ${list || "<p>No audit has been run for the current photos yet.</p>"}
        ${rooms.length ? `<button type="button" class="audit-retake" id="audit-retake-btn">
          Retake / Upload Missing Photos</button>` : ""}
        ${overrideHtml}
      </div>` + warningsHtml;
    highlightRooms(rooms);
    setFinalizeLocked(true, overrideAllowed
      ? "Blocked by the photo audit — fix the listed problems or record a Landlord Override."
      : "Blocked by the photo audit — fix the listed problems and run the audit again.");
    wireAck();

    const retake = document.getElementById("audit-retake-btn");
    if (retake) retake.addEventListener("click", () => focusRoom(rooms[0]));
    // Per-error jump: clicking an error highlights and scrolls to its room.
    box.querySelectorAll(".audit-error").forEach((el, i) => {
      el.style.cursor = "pointer";
      el.addEventListener("click", () => focusRoom(errors[i].room));
    });

    const toggle = document.getElementById("audit-override-toggle");
    if (!toggle) return;
    const form = document.getElementById("audit-override-form");
    toggle.addEventListener("change", () => {
      form.style.display = toggle.checked ? "" : "none";
    });
    document.getElementById("audit-override-confirm").addEventListener("click", async () => {
      const note = document.getElementById("audit-override-note").value.trim();
      if (note.length < 3) {
        alert("The override needs a note — why this report is being finalized anyway.");
        return;
      }
      if (!opts.overrideEndpoint) {
        alert("Override endpoint is not wired yet.");
        return;
      }
      const res = await fetch(opts.overrideEndpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json", "Authorization": "Bearer " + (window.localStorage ? localStorage.getItem("ec_token") : "") },
        body: JSON.stringify({ note }),
      });
      if (!res.ok) {
        alert("The override could not be recorded. The report stays blocked.");
        return;
      }
      const fresh = await res.json();
      if (opts.onOverrideSaved) opts.onOverrideSaved(fresh);
      render(fresh, opts);
    });
  }

  window.TelloInspectGate = { render, focusRoom };
})();
