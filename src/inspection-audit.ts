/**
 * Tello Inspect photo audit. Before a remote inspection report can be finished, every photo goes to Claude
 * together with the property's layout, and Claude returns a strict JSON audit: missing rooms, uncovered wall
 * sections, poor photos, and (for a move-out) what changed since the move-in baseline.
 *
 * The audit fails closed: if Claude can't be reached or its answer can't be read, the report is NOT cleared.
 * The model's own `status` is never trusted: the server sets PASSED only when there are no validation errors.
 * This is an AI photo condition review, never a licensed home inspection, and it never assigns fault.
 */
import Anthropic from "@anthropic-ai/sdk";

export const AUDIT_MODEL = "claude-sonnet-5-5";
const MAX_AUDITS_PER_INSPECTION = 8;
const MAX_BASELINE_PHOTOS = 20;
const MAX_REQUEST_BYTES = 24 * 1024 * 1024; // the API caps a request at 32 MB; base64 adds a third

export interface AuditEnv { DB: D1Database; PHOTOS?: R2Bucket; ANTHROPIC_API_KEY?: string; ANTHROPIC_BASE_URL?: string; }

export interface ValidationError { error_type: "MISSING_ROOM" | "MISSING_ANGLE" | "COVERAGE_GAP" | "POOR_PHOTO_QUALITY"; room: string; description: string; required_action: string; }
export interface CoverageWarning { warning_type: "INFERRED_SPACE_MISSING" | "OPTIONAL_ANGLE"; space: string; description: string; }
export interface Comparison { room: string; item_or_surface: string; move_in_state: string; move_out_state: string; is_new_since_move_in: boolean; classification: "Appears Normal Wear" | "Appears Physical Damage / Alteration" | "Needs Landlord Review"; }
export interface PriorityRepair { room: string; issue: string; severity: "Urgent" | "Moderate" | "Cosmetic"; is_new_since_move_in: boolean; }
export interface RoomReport { room_name: string; overall_condition: "Good" | "Fair" | "Needs Attention"; walls_and_paint: string; flooring: string; ceiling_and_fixtures: string; move_in_comparison_notes: string; }
export interface AuditResult {
  status: "PASSED" | "ERROR_INCOMPLETE_OR_SKIPPED";
  property_audit: { expected_bedrooms: number; detected_bedrooms: number; expected_bathrooms: number; detected_bathrooms: number; square_footage_coverage_assessment: string };
  validation_errors: ValidationError[];
  coverage_warnings: CoverageWarning[];
  move_out_comparison: Comparison[];
  priority_repairs: PriorityRepair[];
  room_by_room_report: RoomReport[];
  disclaimer: string;
}
export interface StoredAudit { id: number; status: string; created_at: string; result: AuditResult; }

