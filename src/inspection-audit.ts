function s(v: unknown, max: number): string { return String(v ?? "").trim().slice(0, max); }
function n(v: unknown, max = 100): number { const x = Number(v); return Number.isFinite(x) ? Math.max(0, Math.min(max, x)) : 0; }
function oneOf<T extends string>(v: unknown, allowed: readonly T[], fallback: T): T { return (allowed as readonly string[]).includes(String(v)) ? (v as T) : fallback; }
function arr(v: unknown, cap: number): Record<string, unknown>[] { return Array.isArray(v) ? v.filter((x) => x && typeof x === "object").slice(0, cap) as Record<string, unknown>[] : []; }

/** Cleans the model's JSON into the exact schema and sets status from the errors, never from the model's own claim. */
export function normalizeAudit(raw: unknown): AuditResult | null {
  if (!raw || typeof raw !== "object") return null;
  const r = raw as Record<string, unknown>;
  const pa = (r.property_audit && typeof r.property_audit === "object" ? r.property_audit : {}) as Record<string, unknown>;
  const validation_errors = arr(r.validation_errors, 60).map((e) => ({
    error_type: oneOf(e.error_type, ["MISSING_ROOM", "MISSING_ANGLE", "COVERAGE_GAP", "POOR_PHOTO_QUALITY"] as const, "MISSING_ANGLE"),
    room: s(e.room, 60), description: s(e.description, 400), required_action: s(e.required_action, 300),
  }));
  const result: AuditResult = {
    status: validation_errors.length ? "ERROR_INCOMPLETE_OR_SKIPPED" : "PASSED",
    property_audit: { expected_bedrooms: n(pa.expected_bedrooms, 20), detected_bedrooms: n(pa.detected_bedrooms, 20), expected_bathrooms: n(pa.expected_bathrooms, 20), detected_bathrooms: n(pa.detected_bathrooms, 20), square_footage_coverage_assessment: s(pa.square_footage_coverage_assessment, 500) },
    validation_errors,
    coverage_warnings: arr(r.coverage_warnings, 30).map((w) => ({ warning_type: oneOf(w.warning_type, ["INFERRED_SPACE_MISSING", "OPTIONAL_ANGLE"] as const, "OPTIONAL_ANGLE"), space: s(w.space, 60), description: s(w.description, 300) })),
    move_out_comparison: arr(r.move_out_comparison, 80).map((c) => ({
      room: s(c.room, 60), item_or_surface: s(c.item_or_surface, 120), move_in_state: s(c.move_in_state, 300), move_out_state: s(c.move_out_state, 300),
      is_new_since_move_in: c.is_new_since_move_in === true,
      classification: oneOf(c.classification, ["Appears Normal Wear", "Appears Physical Damage / Alteration", "Needs Landlord Review"] as const, "Needs Landlord Review"),
    })),
    priority_repairs: arr(r.priority_repairs, 60).map((p) => ({ room: s(p.room, 60), issue: s(p.issue, 300), severity: oneOf(p.severity, ["Urgent", "Moderate", "Cosmetic"] as const, "Moderate"), is_new_since_move_in: p.is_new_since_move_in === true })),
    room_by_room_report: arr(r.room_by_room_report, 40).map((x) => ({
      room_name: s(x.room_name, 60), overall_condition: oneOf(x.overall_condition, ["Good", "Fair", "Needs Attention"] as const, "Fair"),
      walls_and_paint: s(x.walls_and_paint, 500), flooring: s(x.flooring, 500), ceiling_and_fixtures: s(x.ceiling_and_fixtures, 500), move_in_comparison_notes: s(x.move_in_comparison_notes, 500),
    })),
    disclaimer: DISCLAIMER,
  };
  return result;
}

function parseModelJson(text: string): unknown {
  const start = text.indexOf("{"), end = text.lastIndexOf("}");
  if (start < 0 || end <= start) return null;
  try { return JSON.parse(text.slice(start, end + 1)); } catch { return null; }
}

interface Spec { square_footage: number; bedrooms: number; bathrooms: number; property_type: string; baseline_id: number | null; }
interface PhotoRow { id: number; room: string; r2_key: string; shot: string | null; }

/** A fingerprint of the current photo set, so a stored audit is only trusted while the photos are unchanged. */
export async function photoSignature(env: AuditEnv, inspectionId: number): Promise<{ signature: string; count: number }> {
  const rows = (await env.DB.prepare("SELECT id FROM remote_inspection_items WHERE inspection_id = ? ORDER BY id").bind(inspectionId).all<{ id: number }>()).results;
  return { signature: rows.map((x) => x.id).join(","), count: rows.length };
}

export async function latestAudit(env: AuditEnv, inspectionId: number): Promise<(StoredAudit & { signature: string }) | null> {
  const row = await env.DB.prepare("SELECT id, status, result, created_at, signature FROM remote_inspection_audits WHERE inspection_id = ? ORDER BY id DESC LIMIT 1").bind(inspectionId).first<{ id: number; status: string; result: string; created_at: string; signature: string }>();
  if (!row) return null;
  try { return { id: row.id, status: row.status, created_at: row.created_at, signature: row.signature, result: JSON.parse(row.result) as AuditResult }; } catch { return null; }
}

export class AuditError extends Error { constructor(message: string, public status = 502) { super(message); } }

async function loadImages(env: AuditEnv, rows: PhotoRow[], budget: { left: number }): Promise<Array<{ row: PhotoRow; b64: string }>> {
  const out: Array<{ row: PhotoRow; b64: string }> = [];
  for (const row of rows) {
    const obj = env.PHOTOS ? await env.PHOTOS.get(row.r2_key) : null;
    if (!obj) continue;
    const bytes = new Uint8Array(await obj.arrayBuffer());
    if (bytes.byteLength > budget.left) continue;
    budget.left -= bytes.byteLength;
    out.push({ row, b64: toBase64(bytes) });
  }
  return out;
}

function toBase64(bytes: Uint8Array): string {
  let bin = "";
  for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(bin);
}

function mediaType(key: string): "image/jpeg" | "image/png" | "image/webp" { return key.endsWith(".png") ? "image/png" : key.endsWith(".webp") ? "image/webp" : "image/jpeg"; }

/** Runs the audit for one inspection and stores it. Throws AuditError (with a message safe to show) when it can't. */
export async function runAudit(env: AuditEnv, inspection: { id: number; type: string; address: string; notes: string }): Promise<StoredAudit & { signature: string }> {
  if (!env.ANTHROPIC_API_KEY) throw new AuditError("The photo check isn't set up yet. Please try again later.", 503);
  if (!env.PHOTOS) throw new AuditError("Photo storage isn't set up yet.", 503);
  const used = await env.DB.prepare("SELECT COUNT(*) AS n FROM remote_inspection_audits WHERE inspection_id = ?").bind(inspection.id).first<{ n: number }>();
  if (used && used.n >= MAX_AUDITS_PER_INSPECTION) throw new AuditError("This inspection has used all its photo checks. Please contact EC Rental for help.", 429);

  const spec = (await env.DB.prepare("SELECT square_footage, bedrooms, bathrooms, property_type, baseline_id FROM remote_inspection_specs WHERE inspection_id = ?").bind(inspection.id).first<Spec>()) || { square_footage: 0, bedrooms: 0, bathrooms: 0, property_type: "", baseline_id: null };
  const rooms = (await env.DB.prepare("SELECT room FROM remote_inspection_rooms WHERE inspection_id = ? ORDER BY rowid").bind(inspection.id).all<{ room: string }>()).results.map((x) => x.room);
  const photos = (await env.DB.prepare("SELECT i.id, i.room, i.r2_key, s.shot FROM remote_inspection_items i LEFT JOIN remote_inspection_shots s ON s.item_id = i.id WHERE i.inspection_id = ? ORDER BY i.id").bind(inspection.id).all<PhotoRow>()).results;
  if (!photos.length) throw new AuditError("Add at least one photo first.", 400);

  const { signature, count } = await photoSignature(env, inspection.id);
  const budget = { left: MAX_REQUEST_BYTES };
  const current = await loadImages(env, photos, budget);
  if (current.length < photos.length) throw new AuditError("Some photos couldn't be loaded for the check. Please try again.", 502);

  let baseline: Array<{ row: PhotoRow; b64: string }> = [];
  if (inspection.type === "move_out" && spec.baseline_id) {
    const base = (await env.DB.prepare("SELECT i.id, i.room, i.r2_key, s.shot FROM remote_inspection_items i LEFT JOIN remote_inspection_shots s ON s.item_id = i.id WHERE i.inspection_id = ? ORDER BY CASE WHEN s.shot = 'wide' THEN 0 ELSE 1 END, i.id").bind(spec.baseline_id).all<PhotoRow>()).results.slice(0, MAX_BASELINE_PHOTOS);
    baseline = await loadImages(env, base, budget);
  }

  const meta = [
    `Inspection type: ${({ move_in: "Move-In", move_out: "Move-Out", routine: "Routine" } as Record<string, string>)[inspection.type] || "Routine"}`,
    `Property address: ${inspection.address || "not given"}`,
    `Square footage: ${spec.square_footage || "not given"}`,
    `Bedrooms: ${spec.bedrooms || "not given"}`,
    `Bathrooms: ${spec.bathrooms || "not given"}`,
    `Property type: ${spec.property_type || "not given"}`,
    `Selected rooms for this inspection: ${rooms.length ? rooms.join(", ") : "none selected"}`,
    `Move-In baseline provided: ${baseline.length ? "yes (" + baseline.length + " photos)" : "no"}`,
    `Inspection photos follow, each labelled with its photo number, room and shot type.`,
  ].join("\n");

  const content: Array<Record<string, unknown>> = [{ type: "text", text: meta }];
  current.forEach((p, i) => {
    content.push({ type: "text", text: `Move-Out/current photo #${i + 1} | Room: ${p.row.room} | Shot: ${p.row.shot === "wide" ? "wide" : "close-up"}` });
    content.push({ type: "image", source: { type: "base64", media_type: mediaType(p.row.r2_key), data: p.b64 } });
  });
  baseline.forEach((p, i) => {
    content.push({ type: "text", text: `Move-In baseline photo #${i + 1} | Room: ${p.row.room}` });
    content.push({ type: "image", source: { type: "base64", media_type: mediaType(p.row.r2_key), data: p.b64 } });
  });
  content.push({ type: "text", text: "Return only the JSON audit now." });

  let text = "";
  try {
    const client = new Anthropic({ apiKey: env.ANTHROPIC_API_KEY, baseURL: env.ANTHROPIC_BASE_URL || undefined, maxRetries: 1, timeout: 150_000 });
    const msg: any = await client.beta.messages.create({
      model: AUDIT_MODEL, max_tokens: 16000,
      system: AUDIT_PROMPT, messages: [{ role: "user", content }],
      output_config: { effort: "medium" },
    } as any);
    text = (msg.content || []).filter((b: any) => b.type === "text").map((b: any) => b.text).join("");
    if (msg.stop_reason === "refusal") throw new AuditError("The photo check couldn't review these photos. Please try again or contact EC Rental.");
  } catch (err) {
    if (err instanceof AuditError) throw err;
    console.error("[inspection-audit]", err instanceof Error ? err.message : err);
    throw new AuditError("The photo check couldn't finish. Nothing was lost. Please try again in a minute.");
  }
  const result = normalizeAudit(parseModelJson(text));
  if (!result) { console.error("[inspection-audit] unreadable reply", text.slice(0, 300)); throw new AuditError("The photo check gave an unreadable answer. Please try again."); }
  if (inspection.type !== "move_out" || !baseline.length) result.move_out_comparison = [];

  const now = new Date().toISOString();
  const r = await env.DB.prepare("INSERT INTO remote_inspection_audits (inspection_id, signature, status, result, photo_count, created_at) VALUES (?, ?, ?, ?, ?, ?)")
    .bind(inspection.id, signature, result.status, JSON.stringify(result), count, now).run();
  return { id: r.meta.last_row_id as number, status: result.status, created_at: now, signature, result };
}

/** The stored audit for the current photo set, or a fresh one when the photos changed since the last audit. */
export async function auditForCurrentPhotos(env: AuditEnv, inspection: { id: number; type: string; address: string; notes: string }): Promise<StoredAudit & { signature: string }> {
  const [last, sig] = [await latestAudit(env, inspection.id), await photoSignature(env, inspection.id)];
  if (last && last.signature === sig.signature) return last;
  return runAudit(env, inspection);
}
